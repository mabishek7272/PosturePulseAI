import XCTest
import simd

@testable import ARJigCore

/// ARKit camera transform -> the sidecar's camera frame C
/// (x = image right, y = image DOWN, z = optical axis AWAY from the camera).
///
/// These tests exist because a sign error here is SILENT. The clip uploads
/// fine, the server computes pitch from the sidecar, and every clip comes back
/// rejected as `camera_not_level` with nothing in the app to explain why. The
/// HUD would read READY the whole time.
///
/// They also pin the convention mismatch that the AR brief and this repo
/// disagree about: a brief phrased as "90 degrees +/- 3 from the gravity
/// vector" describes the SAME physical state that
/// `services/ml-service/app/geometry/roll_correction.py` and
/// `app/quality/clip_quality.py` call pitch ZERO. Both are defensible
/// conventions; shipping them together is not.
///
/// These live inside the module (`modules/ar-jig/ios/Tests`) rather than in
/// `apps/mobile/ios`, because `apps/mobile/.gitignore` ignores `/ios`: it is
/// generated by Expo prebuild, so a test target placed there would be erased by
/// the next `expo prebuild` and would never be version-controlled in the first
/// place. The podspec's `test_spec` picks these up, so they travel with the
/// module.
final class ARJigGravityTests: XCTestCase {

    /// Builds a camera transform from its basis vectors in ARKit world space.
    ///
    /// ARKit's camera basis (columns of `transform`, in a gravity-aligned world
    /// where +Y is true up) is x = right, y = up, z = toward the viewer, so the
    /// optical axis is -z.
    private func transform(
        right: SIMD3<Float>,
        up: SIMD3<Float>,
        towardViewer: SIMD3<Float>
    ) -> simd_float4x4 {
        simd_float4x4(
            SIMD4<Float>(right.x, right.y, right.z, 0),
            SIMD4<Float>(up.x, up.y, up.z, 0),
            SIMD4<Float>(towardViewer.x, towardViewer.y, towardViewer.z, 0),
            SIMD4<Float>(0, 1.1, 0, 1)   // translation: 1.1 m off the floor
        )
    }

    private func assertVector(
        _ v: [Double]?,
        _ expected: [Double],
        accuracy: Double = 1e-6,
        file: StaticString = #filePath,
        line: UInt = #line
    ) {
        guard let v else { return XCTFail("expected a gravity vector", file: file, line: line) }
        XCTAssertEqual(v.count, 3, file: file, line: line)
        for (a, b) in zip(v, expected) {
            XCTAssertEqual(a, b, accuracy: accuracy, file: file, line: line)
        }
    }

    // MARK: - 1-2: a level camera

    func testLevelCameraLookingHorizontallyGivesImageDown() {
        // Camera level, looking along world -Z. Up is world up, so gravity is
        // purely "image down" -> [0, 1, 0], the value clip-capture.schema.json
        // documents for a level phone filming upright.
        let m = transform(right: [1, 0, 0], up: [0, 1, 0], towardViewer: [0, 0, 1])
        assertVector(ARJigGravity.cameraFrame(cameraTransform: m), [0, 1, 0])
    }

    func testLevelCameraHasZeroPitchInTheRepoConvention() {
        // THE convention assertion. In `asin(|g_z|)` a level camera is pitch
        // ZERO, not 90. If this ever reads 90, the HUD and the server have
        // drifted apart and every clip will be rejected.
        let m = transform(right: [1, 0, 0], up: [0, 1, 0], towardViewer: [0, 0, 1])
        let g = ARJigGravity.cameraFrame(cameraTransform: m)!
        XCTAssertEqual(ARJigMath.pitchDegrees(g), 0, accuracy: 1e-4)
        XCTAssertEqual(ARJigMath.rollDegrees(g), 0, accuracy: 1e-4)
    }

    // MARK: - 3-4: pitch, and the server's hard limit

    func testCameraPitchedDownProducesPositivePitchNotNinety() {
        // Tip the camera down 10 degrees about its right axis: up and
        // toward-viewer rotate, right is unchanged.
        let a = Float(10 * Double.pi / 180)
        let m = transform(
            right: [1, 0, 0],
            up: [0, cos(a), -sin(a)],
            towardViewer: [0, sin(a), cos(a)]
        )
        let g = ARJigGravity.cameraFrame(cameraTransform: m)!
        // 10 degrees in the repo's convention - NOT 80, and NOT 100.
        XCTAssertEqual(ARJigMath.pitchDegrees(g), 10, accuracy: 0.01)
        // Well inside the server's hard limit of 2 x levelToleranceDegrees = 12.
        XCTAssertLessThan(ARJigMath.pitchDegrees(g), 12)
    }

    func testPitchBeyondTheServerLimitIsDetectedAsSuch() {
        let a = Float(15 * Double.pi / 180)
        let m = transform(
            right: [1, 0, 0],
            up: [0, cos(a), -sin(a)],
            towardViewer: [0, sin(a), cos(a)]
        )
        let g = ARJigGravity.cameraFrame(cameraTransform: m)!
        // 15 degrees exceeds 2 x 6, so this clip would be rejected server-side.
        // The default gate (3 degrees) must therefore never let it record.
        XCTAssertGreaterThan(ARJigMath.pitchDegrees(g), 12)
        XCTAssertGreaterThan(ARJigMath.pitchDegrees(g), ARJigThresholds.default.maxPitchDegrees)
    }

    // MARK: - 5-6: roll, and normalisation

    func testRolledCameraShowsUpAsImageX() {
        // Roll 5 degrees about the optical axis: the right edge dips, so gravity
        // gains a +x (image right) component.
        let a = Float(5 * Double.pi / 180)
        let m = transform(
            right: [cos(a), -sin(a), 0],
            up: [sin(a), cos(a), 0],
            towardViewer: [0, 0, 1]
        )
        let g = ARJigGravity.cameraFrame(cameraTransform: m)!
        XCTAssertEqual(ARJigMath.rollDegrees(g), 5, accuracy: 0.01)
        // Roll must not leak into pitch: they are measured independently and the
        // server gates only on pitch.
        XCTAssertEqual(ARJigMath.pitchDegrees(g), 0, accuracy: 0.01)
    }

    func testResultIsAlwaysUnitLength() {
        // `buildArJigSidecar` rejects any frame whose gravity is not unit
        // length, so a non-unit vector here would fail the whole upload rather
        // than one frame.
        let a = Float(23 * Double.pi / 180)
        let m = transform(
            right: [cos(a), -sin(a), 0],
            up: [sin(a) * cos(a), cos(a) * cos(a), -sin(a)],
            towardViewer: [sin(a) * sin(a), cos(a) * sin(a), cos(a)]
        )
        let g = ARJigGravity.cameraFrame(cameraTransform: m)!
        XCTAssertEqual(g.map { $0 * $0 }.reduce(0, +), 1, accuracy: 1e-9)
    }

    // MARK: - 7-8: refusals

    func testDegenerateTransformYieldsNilRatherThanAPlaceholder() {
        // CLAUDE.md rule 3: never fabricate a measurement. A zero basis must not
        // silently become [0, 0, 0] in the sidecar, which would tell the server
        // the device was in free fall.
        let m = simd_float4x4(
            SIMD4<Float>(0, 0, 0, 0), SIMD4<Float>(0, 0, 0, 0),
            SIMD4<Float>(0, 0, 0, 0), SIMD4<Float>(0, 1, 0, 1)
        )
        XCTAssertNil(ARJigGravity.cameraFrame(cameraTransform: m))
    }

    func testGateThresholdsStayInsideTheServersHardLimit() {
        // `levelToleranceDegrees` is 6 for every step in the v0 battery, and
        // `clip_quality.py` rejects pitch > 2 x tolerance. A gate that PASSES
        // must never be able to produce a server-rejected clip, or the operator
        // gets a green light for a capture that cannot be analysed.
        XCTAssertEqual(ARJigThresholds.serverMaxPitchDegrees, 12.0, accuracy: 1e-9)
        XCTAssertLessThan(
            ARJigThresholds.default.maxPitchDegrees,
            ARJigThresholds.serverMaxPitchDegrees
        )
    }
}
